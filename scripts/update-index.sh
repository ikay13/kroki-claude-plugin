#!/usr/bin/env bash
# update-index.sh — Regenerate diagrams/INDEX.md from dual-render outputs.
#
# Usage:
#   update-index.sh <diagrams-dir>
#
# Scans <diagrams-dir> for <basename>.light.svg files, finds the matching
# source file (first extension match), extracts the first-comment-line purpose,
# and writes a grouped-by-prefix table to <diagrams-dir>/INDEX.md.
#
# Exit codes:
#   0 — INDEX.md written (even if zero diagrams found — file will say so)
#   1 — diagrams dir missing

set -euo pipefail

if [[ $# -lt 1 ]]; then
    echo "Usage: update-index.sh <diagrams-dir>" >&2
    exit 1
fi

DIAGRAMS_DIR="$1"

if [[ ! -d "$DIAGRAMS_DIR" ]]; then
    echo "Error: diagrams dir not found: $DIAGRAMS_DIR" >&2
    exit 1
fi

SOURCE_EXTS=(
    puml pu iuml mmd gv dot d2 bpmn dbml nml pik sbob dsl vhdl tex uxf
    adia bdia ndia pdia rdia sdia vega vegalite wavedrom wireviz excalidraw
    ditaa erd
)

find_source() {
    local basename="$1"
    local ext
    for ext in "${SOURCE_EXTS[@]}"; do
        if [[ -f "$DIAGRAMS_DIR/${basename}.${ext}" ]]; then
            echo "${basename}.${ext}"
            return 0
        fi
    done
    return 1
}

extract_purpose() {
    local src_path="$1"
    local line
    line="$(awk 'NF { print; exit }' "$src_path" 2>/dev/null || true)"
    if [[ -z "$line" ]]; then
        echo "(no purpose comment)"
        return
    fi
    # Strip leading whitespace + one comment token + optional space.
    # Note: use / as sed delimiter to avoid conflict with | alternation operator.
    line="$(echo "$line" | sed -E 's/^[[:space:]]*(\/\/|#|'"'"'|%%|--)[[:space:]]?//')"
    if [[ -z "$line" ]]; then
        echo "(no purpose comment)"
    else
        echo "$line"
    fi
}

declare -A BY_PREFIX=()

shopt -s nullglob
for light_svg in "$DIAGRAMS_DIR"/*.light.svg; do
    basename="$(basename "$light_svg" .light.svg)"
    src=""
    src="$(find_source "$basename" || true)"
    if [[ -n "$src" ]]; then
        purpose="$(extract_purpose "$DIAGRAMS_DIR/$src")"
    else
        purpose="(no purpose comment)"
        src="(none)"
    fi

    prefix="${basename%%-*}"
    date_str="$(date -r "$light_svg" +%Y-%m-%d)"

    row="| [[${basename}.light.svg|${basename}]] | ${purpose} | ${date_str} | ${src} |"
    BY_PREFIX[$prefix]+="${row}"$'\n'
done
shopt -u nullglob

TMP="$(mktemp)"
trap 'mv "$TMP" ~/.local/share/Trash/files/update-index-tmp-$(date +%Y%m%d_%H%M%S) 2>/dev/null || true' EXIT

{
    echo "# Diagram Index"
    echo ""
    echo "_Auto-generated by \`scripts/update-index.sh\`. Hand edits are overwritten._"
    echo ""

    if [[ "${#BY_PREFIX[@]}" -eq 0 ]]; then
        echo "No diagrams found in \`$DIAGRAMS_DIR\`."
    else
        for prefix in $(printf '%s\n' "${!BY_PREFIX[@]}" | sort); do
            echo "## ${prefix}"
            echo ""
            echo "| Diagram | Purpose | Last Updated | Source |"
            echo "|---------|---------|--------------|--------|"
            printf '%s' "${BY_PREFIX[$prefix]}" | sort
            echo ""
        done
    fi
} > "$TMP"

mv "$TMP" "$DIAGRAMS_DIR/INDEX.md"
trap - EXIT
echo "Updated: $DIAGRAMS_DIR/INDEX.md"
